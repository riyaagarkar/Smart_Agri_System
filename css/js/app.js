const mockFertilizers = ['Urea (High Nitrogen)', 'DAP (Diammonium Phosphate)', 'NPK 10:26:26', 'MOP (Muriate of Potash)', 'Super Phosphate'];
const mockPesticides = ['Neem Oil Extract', 'Spinosad', 'Bacillus Thuringiensis (Bt)', 'Pyrethrin', 'Copper Fungicide'];
