    toggleVoice() {
        const btn = document.getElementById('voice-btn');
        const input = document.getElementById('chat-input');
        
        if (btn.classList.contains('recording')) {
            btn.classList.remove('recording');
            btn.innerHTML = `<i class="fa-solid fa-microphone"></i>`;
            input.placeholder = translations[currentLang]['chat_placeholder'];
            if(this.recognition) {
                this.recognition.stop();
            }
        } else {
            const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
            
            if (!SpeechRecognition) {
                alert("Speech Recognition API is not supported in this browser. Please use Chrome or Edge.");
                return;
            }

            this.recognition = new SpeechRecognition();
            this.recognition.lang = currentLang === 'en' ? 'en-IN' : (currentLang === 'hi' ? 'hi-IN' : 'mr-IN');
            this.recognition.interimResults = false;
            this.recognition.maxAlternatives = 1;

            this.recognition.onstart = () => {
                btn.classList.add('recording');
                btn.innerHTML = `<i class="fa-solid fa-stop"></i>`;
                input.placeholder = currentLang === 'en' ? "Listening..." : 
                                    currentLang === 'hi' ? "सुन रहा हूँ..." : "ऐकत आहे...";
                input.value = '';
            };

            this.recognition.onresult = (event) => {
                const transcript = event.results[0][0].transcript;
                input.value = transcript;
            };

            this.recognition.onerror = (event) => {
                console.error("Speech recognition error", event.error);
                btn.classList.remove('recording');
                btn.innerHTML = `<i class="fa-solid fa-microphone"></i>`;
                input.placeholder = translations[currentLang]['chat_placeholder'];
            };

            this.recognition.onend = () => {
                btn.classList.remove('recording');
                btn.innerHTML = `<i class="fa-solid fa-microphone"></i>`;
                input.placeholder = translations[currentLang]['chat_placeholder'];
            };

            this.recognition.start();
        }
    }
